function translateText(text) {
  const space = text.match(/^\s*/)[0],
    end = text.match(/\s*$/)[0],
    x = text.trim();
  if (HI[x]) return space + HI[x] + end;
  const names = {
    Kavya: "काव्या",
    Riya: "रिया",
    Anand: "आनंद",
    Gaurav: "गौरव",
  };
  if (/^Namaste, /.test(x)) return "नमस्ते, " + (names[x.slice(9)] || "मित्र");
  if (/^Welcome, /.test(x))
    return "स्वागत है, " + (names[x.split(", ")[1]?.split(" ")[0]] || "मित्र");
  if (/^\d+ seconds remaining$/.test(x)) return x.split(" ")[0] + " सेकंड बाकी";
  if (/^\d+ day practice streak$/.test(x))
    return x.split(" ")[0] + " दिन का अभ्यास";
  return text;
}
function applyPreferences() {
  document.documentElement.lang = state.language === "hi" ? "hi" : "en";
  document.body.dataset.theme = state.theme === "dark" ? "dark" : "light";
  if (state.language !== "hi") return;
  const root = document.getElementById("app");
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n;
  const pending = [];
  while ((n = walker.nextNode())) {
    if (!n.parentElement.closest("script,style,pre,code")) pending.push(n);
  }
  for (const node of pending) {
    const t = translateText(node.nodeValue);
    if (t !== node.nodeValue) node.nodeValue = t;
  }
  for (const el of root.querySelectorAll("[aria-label],[placeholder]"))
    for (const a of ["aria-label", "placeholder"]) {
      const old = el.getAttribute(a);
      if (old) {
        const t = translateText(old);
        if (t !== old) el.setAttribute(a, t);
      }
    }
}
